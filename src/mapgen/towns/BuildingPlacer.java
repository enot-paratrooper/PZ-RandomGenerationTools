package mapgen.towns;

import mapgen.core.Chunk;
import mapgen.core.GenContext;

/**
 * Точка расширения: заполнение города зданиями и объектами.
 *
 * <p>Сюда встанет мост к генератору комнат/зданий (.tbx): участок квартала — это готовый
 * прямоугольник с размерами и типом района, то есть ровно тот вход, который ждёт
 * BuildingParameter (размер, ориентация, набор коллекций под тип района).
 * {@link Town.Facility} — то же самое, но с заранее известным назначением здания.
 *
 * <p><b>Инвариант:</b> реализация не должна иметь изменяемых полей — один экземпляр
 * разделяется всеми потоками растеризации (см. {@link mapgen.core.Generator}). Писать
 * разрешено только в переданный {@link Chunk}, и только в пределах его границ.
 */
public interface BuildingPlacer {
    /**
     * @param block квартал; может выходить за границы блока карты — координаты обрезать самому
     */
    void place(GenContext ctx, Chunk chunk, Town town, Town.Block block);

    /**
     * Инфраструктурное здание с заранее известным назначением. Прямоугольник уже свободен:
     * участок под ним исключён из застройки квартала.
     */
    void placeFacility(GenContext ctx, Chunk chunk, Town town, Town.Facility facility);
}
