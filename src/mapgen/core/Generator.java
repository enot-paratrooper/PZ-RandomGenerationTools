package mapgen.core;

/**
 * Шаг генерации одного блока.
 *
 * <p><b>Инвариант многопоточности:</b> реализация не должна изменять ничего, кроме переданного
 * Chunk и своего GenContext. Всё общее (World, WaterMask) — только чтение. Именно поэтому
 * трассировка рек больше не запускается из RiverGenerator: это была мутация глобального состояния
 * внутри шага конвейера.
 *
 * <p>Один экземпляр генератора разделяется всеми потоками, поэтому полей у него быть не должно.
 */
public interface Generator {
    String name();
    void generate(GenContext ctx, Chunk chunk);
}
