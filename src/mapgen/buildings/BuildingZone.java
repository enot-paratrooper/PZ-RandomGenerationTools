package mapgen.buildings;

/**
 * AI: Зона пула построек — верхний уровень классификации из {@code building_pool.json}.
 * Имя константы совпадает с ключом в манифесте, поэтому сопоставление идёт по
 * {@link #valueOf(String)} без отдельной таблицы.
 *
 * <p>Зона отвечает на вопрос «в каком районе города эта постройка уместна», роль
 * ({@link BuildingDef#role()}) — на вопрос «чем именно она является внутри зоны».
 * Инфраструктурные здания подбираются по роли, рядовая застройка — по зоне.
 */
public enum BuildingZone {
    /** Частный сектор: дома и недострой. Основа любого жилого квартала. */
    RESIDENTIAL_LOW,
    /** Многоквартирные дома и гостиницы. Крупные, их мало (31 запись). */
    RESIDENTIAL_DENSE,
    /** Трейлеры. Отдельная зона, потому что в обычном пригороде смотрятся чужеродно. */
    TRAILER_PARK,
    /** Магазины и офисы. */
    COMMERCIAL_RETAIL,
    /** Общепит и развлечения. */
    FOOD_ENTERTAINMENT,
    /** Заправки, автосервисы, автосалоны. */
    AUTOMOTIVE_FUEL,
    /** Промка вместе с бытовками (роль {@code site_office}). */
    INDUSTRIAL,
    /** Полиция, церкви, школы, транспорт, пожарные, госучреждения. */
    CIVIC,
    /** Медицина. В пуле её всего девять штук, см. отчёт. */
    MEDICAL,
    /** Фермы и сельхозпостройки. */
    RURAL_FARM,
    /** Военные объекты и застройка базы. */
    MILITARY,
    /** Парковые объекты и летний лагерь. */
    PARK_PUBLIC,
    /**
     * Заполнение дворов: сараи, гаражи, патио, биотуалеты, брошенные грузовики.
     * В общий пул выбора участка не идёт никогда — иначе на углу перекрёстка встанет сарай
     * 6x6 вместо дома. Ставится вторым проходом внутри уже застроенного участка.
     */
    FILLER_PROP,
    /**
     * Уникальные объекты (мост, водокачка, вышка). Через обычный BSP-квартал не проходят,
     * ставятся только точечно; в долевые веса районов не входят.
     */
    SPECIAL_LANDMARK;

    private static final BuildingZone[] VALUES = values();

    /** Зона по ключу манифеста или {@code null}, если ключ незнаком. */
    public static BuildingZone byKey(String key) {
        for (BuildingZone z : VALUES) if (z.name().equals(key)) return z;
        return null;
    }

    public static int count() { return VALUES.length; }
}
